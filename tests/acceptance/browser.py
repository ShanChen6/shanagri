"""Run on the isolated acceptance stack after api.mjs."""
import os
import urllib.request
from playwright.sync_api import sync_playwright, expect

BASE = "http://127.0.0.1:3000"
with sync_playwright() as pw:
    browser = pw.chromium.launch()
    owner = browser.new_page(viewport={"width": 375, "height": 812})
    owner.on("dialog", lambda dialog: dialog.accept())
    owner.goto(BASE + "/chu-trang-trai/don")
    expect(owner.get_by_role("main")).to_have_count(1)
    navigation = owner.get_by_role("navigation", name="Điều hướng chính")
    expect(navigation.get_by_role("link", name="Chủ trại")).to_have_attribute("aria-current", "page")
    owner.keyboard.press("Tab")
    expect(owner.get_by_role("link", name="Chuyển đến nội dung chính")).to_be_focused()
    owner.keyboard.press("Enter")
    expect(owner.get_by_role("main")).to_be_focused()
    expect(owner.get_by_role("link", name="Shanagri", exact=True)).to_have_attribute("href", "/")
    login = owner.get_by_role("button", name="Xem danh sách")
    expect(login).to_have_attribute("type", "submit")
    owner.get_by_label("Mã truy cập chủ trang trại").fill(os.environ["DEMO_OWNER_TOKEN"])
    owner.get_by_label("Mã truy cập chủ trang trại").press("Enter")
    owner.get_by_label("Tên lô").fill("Lô nghiệm thu UI")
    owner.get_by_label("Vùng trồng").select_option("zone-cam")
    owner.get_by_label("Ngày bắt đầu").fill("2026-04-01")
    owner.get_by_label("Dự kiến thu hoạch").fill("2026-04-30")
    owner.get_by_text("Lưu lô nháp", exact=True).click()
    draft = owner.locator("li").filter(has_text="Lô nghiệm thu UI")
    draft.get_by_label("Giá (₫/kg)").fill("37000")
    draft.get_by_label("Hạn mức (kg)").fill("100")
    draft.get_by_text("Xem lại và mở bán").click()
    expect(draft).to_have_count(0)
    buyers = []
    for kg in [30, 25, 25]:
        buyer = browser.new_page()
        buyer.goto(BASE + "/cho-nong-san")
        search = buyer.get_by_label("Tìm lô nông sản")
        search.fill("lo nghiem thu ui")
        buyer.get_by_label("Tình trạng nhận đơn").select_option("available")
        buyer.get_by_role("button", name="Áp dụng").click()
        expect(buyer.get_by_role("article")).to_have_count(1)
        buyer.locator("article").filter(has_text="Lô nghiệm thu UI").get_by_role("link", name="Đặt trước").click()
        phone = "090000002" + str(len(buyers))
        buyer.get_by_label("Số điện thoại",exact=True).fill(phone)
        buyer.get_by_label("Số kg").fill(str(kg))
        buyer.get_by_role("button", name="Giữ chỗ").click()
        link = buyer.get_by_role("link", name="Tra cứu đơn vừa đặt")
        expect(link).to_be_visible()
        code = buyer.url.split("/lo/")[1].split("#")[0]
        if not buyers:
            offer = owner.locator("section").filter(
                has=owner.get_by_role("heading", name=f"Lô {code}", exact=True)
            )
            offer.get_by_role("button", name="Tạm dừng nhận đơn").click()
            reopen = offer.get_by_role("button", name="Mở lại", exact=True)
            expect(reopen).to_be_enabled()
            buyer.bring_to_front()
            expect(buyer.get_by_text("Lô đang tạm dừng nhận đặt trước.")).to_be_visible(timeout=20000)
            expect(buyer.get_by_role("button", name="Giữ chỗ")).to_have_count(0)
            expect(link).to_be_visible()
            reopen.click()
            expect(offer.get_by_role("button", name="Tạm dừng nhận đơn")).to_be_enabled()
        link.click()
        req = urllib.request.Request("http://127.0.0.1:4599/+84"+phone[1:],headers={"Authorization":"Bearer "+os.environ["SMS_WEBHOOK_TOKEN"]})
        otp_field = buyer.get_by_label("Mã OTP")
        verify = buyer.get_by_role("button", name="Xác minh số điện thoại")
        expect(verify).to_be_disabled()
        otp_field.fill(urllib.request.urlopen(req).read().decode())
        expect(verify).to_be_enabled()
        otp = otp_field.input_value()
        with buyer.expect_response(lambda response: "/api/lookup" in response.url and response.request.method == "GET"):
            buyer.get_by_role("button", name="Cập nhật trạng thái").click()
        expect(otp_field).to_have_value(otp)
        otp_field.press("Enter")
        expect(buyer.get_by_text("Trạng thái: Chờ xác nhận")).to_be_visible()
        buyers.append(buyer)
    owner.get_by_role("button", name="Xem danh sách").click()
    status_filter = owner.get_by_label("Trạng thái đơn")
    status_filter.select_option("PENDING")
    owner.get_by_role("button", name="Áp dụng bộ lọc").click()
    expect(owner.get_by_text("3 đơn phù hợp", exact=False)).to_be_visible()
    for index in range(len(buyers)):
        owner.get_by_role("button", name="Xác nhận", exact=True).first.click()
        expect(owner.get_by_role("button", name="Xác nhận", exact=True)).to_have_count(2-index)
    expect(owner.get_by_role("heading", name="Không tìm thấy đơn")).to_be_visible()
    expect(status_filter).to_have_value("PENDING")
    owner.get_by_role("button", name="Xóa bộ lọc").click()
    expect(status_filter).to_have_value("all")
    lot = owner.locator("section").filter(has=owner.get_by_label("Ngày thực thu")).filter(has_text=code)
    lot.get_by_label("Ngày thực thu").fill("2026-04-30")
    lot.get_by_label("Sản lượng thực thu").fill("65")
    lot.get_by_role("button", name="Chốt thu hoạch").click()
    owner.get_by_role("button", name="Xem trước phân bổ").last.wait_for()
    # Select the intended lot even if several harvested lots exist.
    panel = owner.locator("section").filter(has_text=code).filter(has=owner.get_by_text("Xem đơn đang giữ", exact=True))
    panel.get_by_role("button", name="Xem trước phân bổ").click()
    table_name = f"Phân bổ lô {code}"
    region = panel.get_by_role("region", name=table_name, exact=True)
    expect(region.get_by_role("table", name=table_name, exact=True)).to_be_visible()
    region.focus()
    expect(region).to_be_focused()
    assert owner.evaluate("document.documentElement.scrollWidth <= window.innerWidth"), "Trang phân bổ tràn ngang"
    expect(panel.get_by_role("spinbutton")).to_have_count(0)
    panel.get_by_role("button", name="Chốt phân bổ", exact=True).click()
    expect(panel.get_by_text("Chốt giao 65 kg cho 3 đơn", exact=False)).to_be_visible()
    expect(panel.get_by_text("Phân bổ đã chốt", exact=False)).to_have_count(0)
    panel.get_by_role("button", name="Xác nhận chốt phân bổ").click()
    expect(panel.get_by_text("Phân bổ đã chốt", exact=False)).to_be_visible()
    with owner.expect_download() as downloaded:
        panel.get_by_role("button", name="Tải danh sách soạn hàng (CSV)").click()
    packing = downloaded.value
    assert packing.suggested_filename == f"soan-hang-{code}.csv"
    with open(packing.path(), encoding="utf-8-sig") as csv_file:
        assert len(csv_file.read().splitlines()) == 4
    first_order = region.get_by_role("row").nth(1)
    first_order.get_by_role("button", name="Đánh dấu đã soạn").click()
    expect(first_order.get_by_text("Đã soạn hàng", exact=True)).to_be_visible()
    first_order.get_by_role("button", name="Đánh dấu đã giao").click()
    expect(panel.get_by_text("Đã soạn 1/3 đơn · Đã giao 1/3 đơn")).to_be_visible()
    owner.get_by_label("Lô nông sản").select_option(code)
    owner.get_by_role("button", name="Áp dụng bộ lọc").click()
    queue = owner.get_by_role("region", name="Hàng đợi soạn và giao")
    queue.get_by_role("button", name="Chờ soạn hàng (2)").click()
    expect(owner.get_by_label("Tiến độ soạn và giao")).to_have_value("packing")
    bulk = owner.get_by_role("region", name="Xử lý nhiều đơn")
    pack_selected = bulk.get_by_role("button", name="Đánh dấu đã soạn các đơn đã chọn")
    expect(pack_selected).to_be_disabled()
    bulk.get_by_role("button", name="Chọn tất cả trên trang").click()
    expect(bulk.get_by_text("Đã chọn 2/2 đơn", exact=False)).to_be_visible()
    pack_selected.click()
    expect(queue.get_by_role("button", name="Chờ giao (2)")).to_be_visible()
    expect(bulk.get_by_text("Đã cập nhật 2/2 đơn.")).to_be_visible()
    expect(panel.get_by_text("Đã soạn 3/3 đơn · Đã giao 1/3 đơn")).to_be_visible()
    expect(pack_selected).to_be_disabled()
    expect(owner.get_by_label("Tiến độ soạn và giao")).to_have_value("packing")
    for index, (buyer, ordered, assigned) in enumerate(zip(buyers,[30,25,25],[30,25,10])):
        buyer.reload()
        expect(buyer.get_by_text(f"Đã đặt: {ordered} kg · Được phân bổ: {assigned} kg")).to_be_visible()
        expect(buyer.get_by_text("Giá trị theo số lượng giao:", exact=False)).to_be_visible()
        expect(buyer.get_by_text("Đã giao" if index == 0 else "Đã soạn hàng", exact=True)).to_be_visible()
    queue.get_by_role("button", name="Chờ giao (2)").click()
    expect(owner.get_by_label("Tiến độ soạn và giao")).to_have_value("delivery")
    bulk.get_by_role("button", name="Chọn tất cả trên trang").click()
    expect(bulk.get_by_text("Đã chọn 2/2 đơn trên trang này · 35 kg")).to_be_visible()
    bulk.get_by_role("button", name="Đánh dấu đã giao các đơn đã chọn").click()
    expect(queue.get_by_role("button", name="Đã giao (3)")).to_be_visible()
    expect(panel.get_by_text("Đã soạn 3/3 đơn · Đã giao 3/3 đơn")).to_be_visible()
    expect(bulk.get_by_text("Đã cập nhật 2/2 đơn.")).to_be_visible()
    for buyer in buyers[1:]:
        buyer.get_by_role("button", name="Cập nhật trạng thái").click()
        expect(buyer.get_by_text("Đã giao", exact=True)).to_be_visible()
    # Both independent tabs initially saw 35 kg on the February fixture.
    first, late = browser.new_page(), browser.new_page()
    for tab in (first, late):
        tab.goto(BASE + "/lo/CAM-2026-02")
        expect(tab.get_by_label("Số kg")).to_have_attribute("max", "35")
        tab.get_by_label("Số điện thoại",exact=True).fill("0900000031" if tab==first else "0900000032")
        tab.get_by_label("Số kg").fill("25")
    first.get_by_role("button", name="Giữ chỗ").click()
    expect(first.get_by_role("link", name="Tra cứu đơn vừa đặt")).to_be_visible()
    # The next poll can already have prevented submission client-side.
    submit = late.get_by_role("button", name="Giữ chỗ")
    if submit.is_enabled():
        submit.evaluate("(button) => button.click()")
    expect(late.get_by_label("Số kg")).to_have_attribute("max", "10", timeout=20000)
    expect(late.get_by_label("Số kg")).to_have_value("25")
    expect(late.get_by_role("link", name="Tra cứu đơn vừa đặt")).to_have_count(0)
    late.get_by_label("Số kg").fill("10")
    submit.click()
    expect(late.get_by_role("link", name="Tra cứu đơn vừa đặt")).to_be_visible()
    browser.close()
